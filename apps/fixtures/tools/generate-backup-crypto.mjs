// Generates backup-crypto.json with Node's crypto, an implementation
// independent of both native apps. Format (all Noah backups, v1 and v2):
//   [version:1][salt:16][nonce:12][AES-256-GCM ciphertext][tag:16]
//   key = PBKDF2-HMAC-SHA256(UTF-8 mnemonic, salt, 600000, 32), no AAD.
// Run: node apps/fixtures/tools/generate-backup-crypto.mjs
import { createCipheriv, pbkdf2Sync } from "node:crypto";
import { writeFileSync } from "node:fs";

const ABANDON =
  "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about";
const LEGAL =
  "legal winner thank year wave sausage worth useful legal winner thank yellow";

const seq = (start, length) => Buffer.from(Array.from({ length }, (_, i) => (start + i) & 0xff));

function seal({ version, mnemonic, salt, nonce, plaintext }) {
  const key = pbkdf2Sync(Buffer.from(mnemonic, "utf8"), salt, 600_000, 32, "sha256");
  const cipher = createCipheriv("aes-256-gcm", key, nonce);
  const ciphertext = Buffer.concat([cipher.update(plaintext), cipher.final()]);
  return Buffer.concat([Buffer.from([version]), salt, nonce, ciphertext, cipher.getAuthTag()]);
}

const inputs = [
  {
    name: "v1 legacy short text",
    version: 1,
    mnemonic: ABANDON,
    salt: seq(0x00, 16),
    nonce: seq(0xa0, 12),
    plaintext: Buffer.from("hello noah", "utf8"),
  },
  {
    name: "v2 snapshot binary 300 bytes",
    version: 2,
    mnemonic: ABANDON,
    salt: seq(0x10, 16),
    nonce: seq(0xb0, 12),
    plaintext: seq(0x00, 300),
  },
  {
    name: "v2 other mnemonic",
    version: 2,
    mnemonic: LEGAL,
    salt: seq(0x80, 16),
    nonce: seq(0x40, 12),
    plaintext: Buffer.from('{"formatVersion":2}', "utf8"),
  },
  {
    name: "v2 empty plaintext",
    version: 2,
    mnemonic: LEGAL,
    salt: seq(0xf0, 16),
    nonce: seq(0x01, 12),
    plaintext: Buffer.alloc(0),
  },
];

const cases = inputs.map((c) => ({
  name: c.name,
  input: {
    version: c.version,
    mnemonic: c.mnemonic,
    saltHex: c.salt.toString("hex"),
    nonceHex: c.nonce.toString("hex"),
    plaintextHex: c.plaintext.toString("hex"),
  },
  expected: { envelopeHex: seal(c).toString("hex") },
}));

const out = new URL("../backup-crypto.json", import.meta.url);
writeFileSync(
  out,
  JSON.stringify(
    {
      description:
        "Noah encrypted backup envelope vectors generated by tools/generate-backup-crypto.mjs (Node crypto). Both apps must encrypt to exactly these bytes with the given salt/nonce and decrypt them back.",
      cases,
    },
    null,
    2,
  ) + "\n",
);
console.log(`wrote ${cases.length} cases`);
