// Generates backup-archives.json: complete backup files built the way the
// RN app builds them, but with Node's crypto and Info-ZIP's `zip`, so neither
// the cipher nor the zip writer is shared with the apps (both use ZIPFoundation).
//   v2 (encryptWalletSnapshot): manifest.json + db.sqlite at the zip root,
//      envelope version 2, raw bytes.
//   v1 (createBackup): backup_staging/noah-data-<variant>/… zipped with its
//      parent and directory entries, envelope version 1, base64 text.
// Envelope: [version:1][salt:16][nonce:12][AES-256-GCM ciphertext][tag:16],
// key = PBKDF2-HMAC-SHA256(UTF-8 mnemonic, salt, 600000, 32).
// Run: node apps/fixtures/tools/generate-backup-archives.mjs  (needs `zip`)
import { createCipheriv, createHash, pbkdf2Sync } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, utimesSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const MNEMONIC =
  "legal winner thank year wave sausage worth useful legal winner thank yellow";
const FIXED_TIME = new Date("2026-10-19T12:00:00Z");

const seq = (start, length) => Buffer.from(Array.from({ length }, (_, i) => (start * 7 + i * 13) & 0xff));
const sha256 = (data) => createHash("sha256").update(data).digest("hex");

function seal(version, plaintext, salt, nonce) {
  const key = pbkdf2Sync(Buffer.from(MNEMONIC, "utf8"), salt, 600_000, 32, "sha256");
  const cipher = createCipheriv("aes-256-gcm", key, nonce);
  const ciphertext = Buffer.concat([cipher.update(plaintext), cipher.final()]);
  return Buffer.concat([Buffer.from([version]), salt, nonce, ciphertext, cipher.getAuthTag()]);
}

/** Writes `files` under `dir`, then zips `entries` (relative to `dir`). */
function zipFiles(files, entries, recurse) {
  const dir = mkdtempSync(join(tmpdir(), "noah-fixture-"));
  try {
    for (const [path, data] of Object.entries(files)) {
      const full = join(dir, path);
      mkdirSync(join(full, ".."), { recursive: true });
      writeFileSync(full, data);
    }
    const touch = (path) => utimesSync(join(dir, path), FIXED_TIME, FIXED_TIME);
    for (const path of Object.keys(files)) {
      touch(path);
      const parts = path.split("/");
      for (let i = 1; i < parts.length; i++) touch(parts.slice(0, i).join("/"));
    }
    // -X: no extra attributes, -9: deflate, -q: quiet.
    execFileSync("zip", ["-X", "-9", "-q", ...(recurse ? ["-r"] : []), "out.zip", ...entries], { cwd: dir });
    return readFileSync(join(dir, "out.zip"));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

// JSON.stringify order from backupService.ts.
const manifest = {
  formatVersion: 2,
  createdAt: "2026-10-19T12:00:00.000Z",
  snapshotSha256: "",
  network: "regtest",
  walletFingerprint: "fixture1",
  serverPubkey: "02" + "11".repeat(32),
  mailboxPubkey: null,
  barkSchemaVersion: 42,
};
const snapshot = seq(1, 3000);
manifest.snapshotSha256 = sha256(snapshot);
const v2Zip = zipFiles(
  { "manifest.json": JSON.stringify(manifest), "db.sqlite": snapshot },
  ["manifest.json", "db.sqlite"],
  false,
);
const v2File = seal(2, v2Zip, seq(2, 16), seq(3, 12));

const legacyFiles = {
  "backup_staging/noah-data-regtest/db.sqlite": seq(4, 2048),
  "backup_staging/noah-data-regtest/db.sqlite-wal": seq(5, 512),
  "backup_staging/noah-data-regtest/bdk/wallet.json": Buffer.from('{"fixture":true}', "utf8"),
};
const legacyZip = zipFiles(legacyFiles, ["backup_staging"], true);
const legacyText = seal(1, legacyZip, seq(6, 16), seq(7, 12)).toString("base64");

const prefix = "backup_staging/noah-data-regtest/";
const fixture = {
  description:
    "Complete backup files generated by tools/generate-backup-archives.mjs with Node crypto and Info-ZIP, independent of the apps' zip and crypto code. Both apps must open them and unpack exactly the expected files.",
  cases: [
    {
      name: "v2 snapshot backup",
      input: { kind: "v2", variant: "regtest", mnemonic: MNEMONIC, fileBase64: v2File.toString("base64") },
      expected: { manifest, files: { "db.sqlite": sha256(snapshot) } },
    },
    {
      name: "v1 legacy directory backup",
      // The downloaded v1 file is itself base64 text.
      input: { kind: "legacy", variant: "regtest", mnemonic: MNEMONIC, fileText: legacyText },
      expected: {
        files: Object.fromEntries(
          Object.entries(legacyFiles).map(([path, data]) => [path.slice(prefix.length), sha256(data)]),
        ),
      },
    },
  ],
};

writeFileSync(new URL("../backup-archives.json", import.meta.url), JSON.stringify(fixture, null, 2) + "\n");
