// Generates bitcoin-amount.json from the RN formatter's logic
// (client/src/lib/bitcoinAmount.ts) using Node's ICU, which matches what
// users saw in the React Native app.
// Run: node apps/fixtures/tools/generate-bitcoin-amount.mjs
import { writeFileSync } from "node:fs";

const format = (sats, unit, locale) =>
  unit === "sats" ? `${sats.toLocaleString(locale)} sats` : `₿ ${sats.toLocaleString(locale)}`;

const cases = [];
for (const locale of ["en", "es", "ja", "ko", "sv"]) {
  for (const unit of ["bip177", "sats"]) {
    for (const sats of [0, 1, 999, 1234, 21000, 998900, 2100000000000000]) {
      cases.push({ name: `${locale} ${unit} ${sats}`, input: { sats, unit, locale }, expected: format(sats, unit, locale) });
    }
  }
}

writeFileSync(
  new URL("../bitcoin-amount.json", import.meta.url),
  JSON.stringify(
    {
      description: "formatBitcoinAmount from client/src/lib/bitcoinAmount.ts, rendered with Node ICU. Generated by tools/generate-bitcoin-amount.mjs.",
      cases,
    },
    null,
    2,
  ) + "\n",
);
console.log(`wrote ${cases.length} cases`);
